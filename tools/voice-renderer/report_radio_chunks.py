def render_script(bundle: dict) -> tuple[str, dict]:
    """One readable performance script, preserving selected item order exactly."""
    headings = {}
    for line in bundle["source"].read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"## (A[1-7])\s+—\s+(.+)", line)
        if match:
            headings[match[1]] = line
    counts = Counter()
    lines = [MARKER, "", "# Gästrummet – fullständigt ljudmanus", "",
             "Källrepliker och berättartext återges ordagrant från det svenska manuset, i den ordning de skickades till de valda tagningarna. Rollnamn, delmarkeringar och instruktioner läses inte upp.", "",
             "**RUT**, **HELENA** och **KIM** är skådespelarroller. **BERÄTTARE** är den separata berättarrösten. "
             "Block märkta **Regi — läses inte upp** är manusets scen- och ljudanvisningar, visade här för läsning. "
             "**Rösttagg** visar instruktionen till ElevenLabs. **Tillagd reaktion** markerar separat tillförda skratt eller andetag; dessa är inte källrepliker.", "",
             "Roller: " + "; ".join(f"{role.title()}: {voice['name']}" for role, voice in bundle["cast"].items()) + ". Kim har pronomen hen.", "",
             "Ljuddelarnas ID och tagningar följer " + link("lyssningsöversikten", bundle["output"] / "README.md")
             + ". Delmarkeringarna är läshjälp och innebär inga hörbara aktpresentationer.", ""]
    section = None
    for chunk in bundle["chunks"]:
        pending_locator = True
        counts["chunks"] += 1
        for item in chunk["plan"]["items"]:
            item_section = item.get("section", chunk["section"])
            if item_section != section:
                if item_section not in headings:
                    raise ValueError(f"Missing source section heading: {item_section}")
                lines.extend([headings[item_section], ""])
                section = item_section
            if item.get("kind") == "comment":
                # Leading comments may belong to the previous act. Keep them
                # before the new act heading and its first spoken turn.
                lines.extend([f"> **Regi — läses inte upp:** {item['comment']}", ""])
                counts["unspoken_source_cues"] += 1
                continue
            if pending_locator:
                label = f"Ljuddel {chunk['id']} · {chunk['take']}"
                lines.extend([link(label, chunk["path"]) + f" · källturer {chunk['start']}–{chunk['end']}", ""])
                pending_locator = False
            if item.get("tags"):
                lines.extend([f"*Rösttagg:* `{item['tags']}`", ""])
            if item.get("source_spoken") is True:
                lines.extend([f"**{item['speaker']}:** {item['text']}", ""])
                counts["source_turns"] += 1
                if item.get("kind") == "narration":
                    counts["narration_turns"] += 1
            elif item.get("kind") == "reaction":
                lines.extend([f"**Tillagd reaktion – {item['speaker']}:** {item['text']}", ""])
                counts["added_reaction_turns"] += 1
            else:
                raise ValueError(f"Unknown performance item: {chunk['id']} {item.get('kind')}")
    if (counts["source_turns"] != bundle["source_turns"]
            or counts["unspoken_source_cues"] != bundle["source_cues"]):
        raise ValueError("Combined performance script changed the verified source coverage.")
    return "\n".join(lines), dict(counts)


