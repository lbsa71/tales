MARKER = f"<!-- Generated by {GENERATOR}; safe to regenerate. -->"
SPOKEN = re.compile(r"\*\*([^:*]+):\*\* (.*)")


def load(path: Path) -> dict:
    result = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(result, dict):
        raise ValueError(f"Expected a JSON object: {path}")
    return result


def sha(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def resolved(value: str | Path) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (ROOT / path).resolve()


def check_hash(path: Path, expected: str | None, description: str) -> str:
    actual = sha(path)
    if not expected or actual != expected:
        raise ValueError(f"{description}: checksum does not match: {path}")
    return actual


def escaped(text: object) -> str:
    return str(text).replace("\\", "\\\\").replace("|", "\\|").replace("[", "\\[").replace("]", "\\]").replace("\n", " ")


def link(label: str, path: Path) -> str:
    return f"[{escaped(label)}](<{path.resolve().as_posix()}>)"


def clock(seconds: float | None) -> str:
    if seconds is None:
        return "tid saknas"
    value = max(0, int(round(seconds)))
    hours, remainder = divmod(value, 3600)
    minutes, seconds = divmod(remainder, 60)
    return f"{hours}:{minutes:02}:{seconds:02}" if hours else f"{minutes}:{seconds:02}"


def finite(value) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def wav_info(path: Path) -> dict:
    with wave.open(str(path), "rb") as handle:
        frames, rate = handle.getnframes(), handle.getframerate()
        channels, width = handle.getnchannels(), handle.getsampwidth()
        if not frames or not rate or handle.getcomptype() != "NONE":
            raise ValueError(f"Empty or unsupported WAV: {path}")
        remaining = frames
        while remaining:
            count = min(remaining, 48_000)
            if len(handle.readframes(count)) != count * channels * width:
                raise ValueError(f"Truncated WAV: {path}")
            remaining -= count
    return {"duration_seconds": frames / rate, "frames": frames,
            "sample_rate_hz": rate, "channels": channels, "sample_width_bits": width * 8}


def source_records(path: Path) -> tuple[list[dict], list[tuple[int, str]]]:
    spoken, cues = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        match = SPOKEN.fullmatch(line)
        if match:
            spoken.append({"source_index": len(spoken) + 1, "speaker": match[1], "text": match[2]})
        elif line.startswith("["):
            cues.append((len(spoken), line))
    return spoken, cues


def event_time(chunk: dict, turn: dict, detail: dict | None = None) -> dict:
    """Map an ASR location into the chosen local mix, retaining uncertainty."""
    value = (detail or {}).get("start")
    precision = "ASR word time"
    if not finite(value):
        value = turn.get("start")
        precision = "ASR turn start; missing word has no exact time"
    row = chunk["timeline"].get(turn.get("source_index"))
    if not finite(value) and row:
        value = row.get("raw_start_seconds")
        precision = "turn start from mixed source timeline"
    if not finite(value):
        return {"raw_seconds": None, "local_seconds": None, "global_seconds": None,
                "precision": "no timed words for this turn"}
    local = float(value)
    if chunk["mix"] and chunk["mix"].get("approved_mix_reused_bit_identically") and row:
        # Approved timeline already includes the original 2.2-second opening;
        # this audit's word times still refer to the original dry dialogue.
        reference = turn.get("start") if finite(turn.get("start")) else row["raw_start_seconds"]
        local += row["local_start_seconds"] - reference
    elif chunk["mix"]:
        local += chunk["mix"].get("lead_handle_seconds", 0)
        rate = chunk["audio"]["sample_rate_hz"]
        local += sum(item["frames"] / rate for item in chunk["mix"].get("silence_insertions", [])
                     if item["at_raw_frame"] <= round(value * rate))
    global_time = local + chunk["mix"]["global_start_seconds"] if chunk["mix"] else None
    return {"raw_seconds": round(value, 6), "local_seconds": round(local, 6),
            "global_seconds": round(global_time, 6) if global_time is not None else None,
            "precision": precision}


def collect(index_path: Path, output: Path, revision: str) -> dict:
    index = load(index_path)
    source = resolved(index["source"])
    source_hash = check_hash(source, index["source_sha256"], "Swedish source")
    english_hash = check_hash(ENGLISH_SOURCE, ENGLISH_SHA256, "English source")
    expected_speech, expected_cues = source_records(source)
    if len(expected_speech) != index["spoken_turns"]:
        raise ValueError("Index and source spoken counts differ.")
    selection_path = output / "selection.json"
    selection = load(selection_path) if selection_path.exists() else {}
    ids = {item["id"] for item in index["chunks"]}
    if set(selection) - ids:
        raise ValueError(f"Unknown selected chunk IDs: {sorted(set(selection) - ids)}")
    absent = []
    for spec in index["chunks"]:
        take = selection.get(spec["id"], "take-01")
        if not isinstance(take, str) or not re.fullmatch(r"take-[0-9]{2}", take):
            raise ValueError(f"Invalid take selection: {spec['id']}={take}")
        folder = output / "chunks" / spec["id"] / take
        for name in ("plan.json", "render-manifest.json", "dialogue.wav", "audit.json", "transcript.json", "transcript.meta.json"):
            if not (folder / name).is_file():
                absent.append(str(folder / name))
    if absent:
        raise ValueError("All selected chunks must finish rendering and auditing first. Missing:\n" + "\n".join(absent))
    chunks, actual_speech, actual_cues = [], [], []
    cast = None
    after = 0
    for spec in index["chunks"]:
        take = selection.get(spec["id"], "take-01")
        folder = output / "chunks" / spec["id"] / take
        plan_path = folder / "plan.json"
        plan, manifest, audit = load(plan_path), load(folder / "render-manifest.json"), load(folder / "audit.json")
        frozen_hash = sha(resolved(spec["plan"]))
        check_hash(plan_path, frozen_hash, "Selected plan versus frozen plan")
        check_hash(plan_path, manifest.get("plan_sha256"), "Rendered plan")
        audio_hash = check_hash(folder / "dialogue.wav", manifest.get("wav_sha256"), "Rendered WAV")
        if plan.get("source_sha256_at_preparation") != source_hash:
            raise ValueError(f"Prepared source identity differs: {spec['id']}")
        if plan.get("model_id") != "eleven_v3" or plan.get("language_code") != "sv":
            raise ValueError(f"Unexpected model or language: {spec['id']}")
        for name, path in (("audio", folder / "dialogue.wav"), ("plan", plan_path), ("transcript", folder / "transcript.json")):
            check_hash(path, audit.get("inputs", {}).get(name, {}).get("sha256"), f"Audit input {name}")
        provenance = load(folder / "transcript.meta.json")
        if (provenance.get("status") != "success" or provenance.get("input_sha256") != audio_hash
                or audit.get("transcript_provenance", {}).get("audio_checksum_matches") is not True):
            raise ValueError(f"Transcript provenance does not match selected WAV: {spec['id']}")
        if (audit.get("source_coverage", {}).get("exact_match") is not True
                or audit["source_coverage"].get("source_sha256") != source_hash):
            raise ValueError(f"Source audit is stale or failed: {spec['id']}")
        voices = {role: value["voice_id"] for role, value in plan["voices"].items()}
        if cast is None:
            cast = plan["voices"]
        elif voices != {role: value["voice_id"] for role, value in cast.items()}:
            raise ValueError(f"Cast differs across selected chunks: {spec['id']}")
        source_turns = [item for item in plan["items"] if item.get("source_spoken") is True]
        wanted_indices = list(range(spec["start"], spec["end"] + 1))
        if [item.get("source_index") for item in source_turns] != wanted_indices:
            raise ValueError(f"Wrong source range: {spec['id']}")
        for item in plan["items"]:
            if item.get("source_spoken") is True:
                after = item["source_index"]
                actual_speech.append({key: item[key] for key in ("source_index", "speaker", "text")})
            elif item.get("kind") == "comment":
                actual_cues.append((after, item["comment"]))
        render_items = [item for item in plan["items"] if item.get("kind") != "comment"]
        if [(item["speaker"], item["text"]) for item in render_items] != [(item["speaker"], item["text"]) for item in audit["turns"]]:
            raise ValueError(f"Audit turn ordering differs: {spec['id']}")
        api_chars = sum(len(" ".join(part for part in (item.get("tags", "").strip(), item.get("text", "").strip()) if part)) for item in render_items)
        if api_chars != spec["characters"] or api_chars > 2000:
            raise ValueError(f"API character count differs or exceeds limit: {spec['id']}")
        mix_path = folder / f"{revision}-manifest.json"
        mix = load(mix_path) if mix_path.exists() else None
        path = folder / "dialogue.wav"
        if mix:
            if mix.get("take") != take or mix.get("chunk_id") != spec["id"]:
                raise ValueError(f"Mix identity differs: {mix_path}")
            for name, input_path in (("plan", plan_path), ("dialogue", folder / "dialogue.wav")):
                check_hash(input_path, mix.get("input_hashes", {}).get(name), f"Mix input {name}")
            if not spec.get("reused"):
                check_hash(folder / "audit.json", mix.get("input_hashes", {}).get("asr_timing"), "Mix ASR timing")
            if mix.get("all_source_pcm_preserved_before_gain") is not True:
                raise ValueError(f"Source PCM preservation not verified: {mix_path}")
            path = resolved(mix["path"])
            check_hash(path, mix.get("wav_sha256"), "Mixed WAV")
            if spec.get("reused"):
                origin = load(folder / "approved-origin.json")
                check_hash(path, origin.get("mix_sha256"), "Approved opening mix reuse")
        audio = wav_info(path)
        if mix and (mix["frames"] != audio["frames"] or abs(mix["duration_seconds"] - audio["duration_seconds"]) > 1 / audio["sample_rate_hz"]):
            raise ValueError(f"Mix duration differs from WAV: {path}")
        timeline = {row["source_index"]: row for row in mix.get("source_timeline", [])} if mix else {}
        chunks.append({**spec, "take": take, "folder": folder, "plan": plan,
                       "manifest": manifest, "audit": audit, "mix": mix, "path": path,
                       "audio": audio, "timeline": timeline, "first": source_turns[0],
                       "last": source_turns[-1], "wav_sha256": sha(path)})
    if actual_speech != expected_speech:
        raise ValueError("Selected chunks do not preserve every source turn exactly once and in order.")
    if actual_cues != expected_cues:
        raise ValueError("Selected chunks do not preserve every source cue once at its original position.")
    full_path = output / "mixes" / revision / "manifest.json"
    full = load(full_path) if full_path.exists() else None
    if full:
        expected = [(chunk["id"], chunk["take"], chunk["wav_sha256"]) for chunk in chunks]
        got = [(item["chunk_id"], item["take"], item["wav_sha256"]) for item in full["chunks"]]
        if expected != got:
            raise ValueError("Full mix uses a different take selection or different chunk audio.")
        for item in full["files"]:
            check_hash(resolved(item["path"]), item.get("sha256"), "Full/act export")
        if abs(sum(chunk["audio"]["duration_seconds"] for chunk in chunks) - full["duration_seconds"]) > .001:
            raise ValueError("Full mix duration differs from its selected chunks.")
    return {"index_path": index_path, "index": index, "output": output, "revision": revision,
            "source": source, "source_hash": source_hash, "english_hash": english_hash,
            "chunks": chunks, "cast": cast, "source_turns": len(expected_speech),
            "source_cues": len(expected_cues), "full": full, "full_manifest_path": full_path,
            "selection_path": selection_path}


def candidates(bundle: dict) -> tuple[list[dict], list[dict], dict]:
    lexical, voice_events = [], []
    stats = Counter()
    for chunk in bundle["chunks"]:
        for turn in chunk["audit"]["turns"]:
            if not turn.get("source_spoken"):
                stats["planned_reaction_turns"] += 1
                continue
            stats["source_turns"] += 1
            if turn.get("all_expected_tokens_matched"):
                stats["all_expected_words_matched_turns"] += 1
            if turn.get("asr_fidelity_review_needed"):
                stats["lexical_review_turns"] += 1
            for field in ("missing", "substitutions", "insertions"):
                for detail in turn.get(field, []):
                    stats[field] += 1
                    lexical.append({"chunk_id": chunk["id"], "take": chunk["take"],
                                    "source_index": turn["source_index"], "speaker": turn["speaker"],
                                    "source_text": turn["text"], "kind": field,
                                    "expected": detail.get("expected"), "observed": detail.get("observed"),
                                    **event_time(chunk, turn, detail)})
            if turn.get("differs_from_role_majority"):
                voice_events.append({"chunk_id": chunk["id"], "source_index": turn["source_index"],
                                     "speaker": turn["speaker"], "speaker_id": turn.get("majority_speaker_id"),
                                     "short_evidence": bool(turn.get("speaker_evidence_uncertain")),
                                     "source_text": turn["text"], **event_time(chunk, turn)})
    return lexical, voice_events, dict(stats)


def audio_links(bundle: dict) -> list[str]:
    if not bundle["full"]:
        return ["Helmix och aktfiler finns ännu inte för denna mixversion.", ""]
    files = {Path(item["path"]).name: resolved(item["path"]) for item in bundle["full"]["files"]}
    links = [link(label, files[name]) for name, label in (("gastrummet-sv.wav", "Hela pjäsen · WAV"), ("gastrummet-sv.mp3", "Hela pjäsen · MP3"), ("chunks.m3u", "Spellista")) if name in files]
    acts = [link(f"A{i}", files[f"a{i}-sv.mp3"]) for i in range(1, 8) if f"a{i}-sv.mp3" in files]
    return [" · ".join(links), "", "Akter: " + " · ".join(acts), ""]


