def write_reports(output: Path, files: dict[str, str]) -> None:
    output.mkdir(parents=True, exist_ok=True)
    for name in files:
        path = output / name
        if path.exists():
            if path.is_symlink():
                raise ValueError(f"Refusing to replace a symlink: {path}")
            if name.endswith(".json"):
                safe = load(path).get("generated_by") == GENERATOR
            else:
                safe = path.read_text(encoding="utf-8").startswith(MARKER)
            if not safe:
                raise ValueError(f"Existing report was not generated by this program; preserve or rename it first: {path}")
    for name, content in files.items():
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=output, prefix=f".{name}.", suffix=".tmp", delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(content)
            os.replace(temporary, output / name)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--index", type=Path, default=DEFAULT_INDEX)
    parser.add_argument("--revision", default="mix-v1")
    args = parser.parse_args()
    if not re.fullmatch(r"mix-[a-z0-9][a-z0-9-]*", args.revision):
        parser.error("Use a mix revision such as mix-v1.")
    bundle = collect(args.index.resolve(), args.output.resolve(), args.revision)
    lexical, voice_events, stats = candidates(bundle)
    script, script_counts = render_script(bundle)
    if script_counts.get("added_reaction_turns", 0) != stats.get("planned_reaction_turns", 0):
        raise ValueError("Combined script and selected audits have different reaction counts.")
    summary = {
        "generated_by": GENERATOR, "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "source": {"path": str(bundle["source"]), "sha256": bundle["source_hash"],
                   "exact_input_source_turns": bundle["source_turns"], "exact_source_cues": bundle["source_cues"],
                   "english_original_sha256": bundle["english_hash"]},
        "revision": args.revision, "cast": bundle["cast"], "asr_statistics": stats,
        "lexical_listening_candidates": lexical, "voice_listening_candidates": voice_events,
        "subjective_listening_performed_by_this_program": False,
        "combined_render_script": {"path": str(bundle["output"] / "render-script.md"), **script_counts},
        "chunks": [{"id": chunk["id"], "take": chunk["take"], "path": str(chunk["path"]),
                    "wav_sha256": chunk["wav_sha256"], "mixed": chunk["mix"] is not None,
                    "source_start": chunk["start"], "source_end": chunk["end"],
                    "duration_seconds": chunk["audio"]["duration_seconds"],
                    "first_text": chunk["first"]["text"], "last_text": chunk["last"]["text"]}
                   for chunk in bundle["chunks"]],
    }
    files = {"README.md": render_readme(bundle, stats), "QA.md": render_qa(bundle, lexical, voice_events, stats),
             "render-script.md": script,
             "qa-summary.json": json.dumps(summary, ensure_ascii=False, indent=2) + "\n"}
    write_reports(bundle["output"], files)
    print(json.dumps({"reports": [str(bundle["output"] / name) for name in files],
                      "chunks": len(bundle["chunks"]), "source_turns": bundle["source_turns"],
                      "source_cues": bundle["source_cues"], "asr_statistics": stats,
                      "combined_render_script": script_counts,
                      "lexical_listening_candidates": len(lexical), "voice_listening_candidates": len(voice_events)},
                     ensure_ascii=False, indent=2))
    return 0


